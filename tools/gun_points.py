"""Find where each gun sprite is held (the grip) and where its shots leave (the muzzle), and write
them to src/sim/gunPoints.js, which both the rules (bullet spawn point) and the renderer (sprite
origin, muzzle flash) read. Also saves a preview sheet with the points marked, to check by eye.

Guns are drawn lying flat, muzzle to the right.
  Muzzle: the rightmost column of the sprite; the middle of its opaque pixels.
  Grip: the bottom edge of the gun's body (the most common bottom row) is the "baseline"; parts
  hanging below it are the grip, magazine, stock... The grip is the leftmost one that doesn't
  start at the sprite's left edge (that's a stock). Held at the top of the grip, on the baseline.
Overrides (pixel coordinates) win over the guesses, for any gun the guess gets wrong.

  python tools/gun_points.py public/art preview.png pistol revolver smg ...
"""
import argparse
import json
from collections import Counter
from pathlib import Path

from PIL import Image, ImageDraw

OVERRIDES = {
    "smg": {"grip": [10.5, 9]},  # the guess lands between the grip and the magazine
    "sniper": {"grip": [11, 7]},  # the guess lands on the stock
    "bow": {"grip": [3, 16], "muzzle": [5, 16]},  # held mid-bow; the arrow leaves from the string
    "cards": {"grip": [6, 6], "muzzle": [11, 5]},  # held by the middle of the card
}


def points(im):
    a = im.convert("RGBA")
    w, h = a.size
    px = a.load()
    opaque = lambda x, y: px[x, y][3] > 0
    cols = {x: [y for y in range(h) if opaque(x, y)] for x in range(w)}
    right = max(x for x in range(w) if cols[x])
    ys = cols[right]
    muzzle = [right + 1, (min(ys) + max(ys) + 1) / 2]
    bottoms = {x: max(c) for x, c in cols.items() if c}
    baseline = Counter(bottoms.values()).most_common(1)[0][0]
    # Runs of columns hanging below the baseline.
    runs, run = [], []
    for x in range(w):
        if x in bottoms and bottoms[x] >= baseline + 2:
            run.append(x)
        elif run:
            runs.append(run)
            run = []
    if run:
        runs.append(run)
    left = min(bottoms)
    candidates = [r for r in runs if r[0] > left + 1 and r[-1] < right - w * 0.15]
    if candidates:
        grip_run = candidates[0]
        grip = [(grip_run[0] + grip_run[-1] + 1) / 2, baseline + 1]
        how = "grip below the body"
    else:
        grip = [left + w * 0.3, baseline + 1]
        how = "no grip found: 30% along the bottom"
    r = lambda p: [round(p[0], 1), round(p[1], 1)]
    return {"grip": r(grip), "muzzle": r(muzzle), "size": [w, h]}, how


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("art")
    ap.add_argument("preview")
    ap.add_argument("guns", nargs="+")
    ap.add_argument("--out", default="src/sim/gunPoints.js")
    args = ap.parse_args()
    result = {}
    scale = 8
    tiles = []
    for key in args.guns:
        im = Image.open(Path(args.art) / f"{key}.png").convert("RGBA")
        pts, how = points(im)
        pts.update(OVERRIDES.get(key, {}))
        result[key] = pts
        print(f"{key}: grip {pts['grip']}, muzzle {pts['muzzle']} ({how})")
        big = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
        tile = Image.new("RGBA", (big.width + 40, big.height + 40), (40, 44, 60, 255))
        tile.alpha_composite(big, (20, 20))
        d = ImageDraw.Draw(tile)
        for (x, y), color in ((pts["grip"], (80, 255, 120)), (pts["muzzle"], (255, 80, 80))):
            cx, cy = 20 + x * scale, 20 + y * scale
            d.ellipse((cx - 5, cy - 5, cx + 5, cy + 5), outline=color, width=2)
        d.text((4, 2), key, fill=(255, 255, 0))
        tiles.append(tile)
    sheet = Image.new("RGBA", (max(t.width for t in tiles), sum(t.height for t in tiles)), (40, 44, 60, 255))
    y = 0
    for t in tiles:
        sheet.alpha_composite(t, (0, y))
        y += t.height
    sheet.save(args.preview)
    rows = [f"  {k}: {{ grip: {json.dumps(v['grip'])}, muzzle: {json.dumps(v['muzzle'])}, size: {json.dumps(v['size'])} }}," for k, v in result.items()]
    body = "{\n" + "\n".join(rows) + "\n}"
    Path(args.out).write_text(
        "// Generated by tools/gun_points.py from the gun sprites: where each gun is held (grip) and\n"
        "// where its shots leave (muzzle), in the sprite's pixels (x right, y down; the muzzle points\n"
        "// right). Rerun the tool after changing gun art; fix a bad guess with its OVERRIDES.\n"
        f"export const GUN_POINTS = {body};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
