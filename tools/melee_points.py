"""Measure each melee weapon sprite: how far its tip reaches from where it's held, and write
src/sim/meleePoints.js, which the rules use to put the hit area along the blade (so what you see
is what hits).

Melee sprites lie flat, tip to the right, held at 12% of their width from the left (the ones in
TILTED are drawn tilted 45°, tip up and right, held where it says).

  python tools/melee_points.py public/art katana bolivar ...
"""
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image

# Weapons drawn tilted: (held at x, y as shares of the size; the direction the tip points).
DIAG = -math.pi / 4
TILTED = {
    "knife": (0.2, 0.8, DIAG),
    "halberd": (0.3, 0.7, DIAG),
    "morningstar": (0.25, 0.75, DIAG),
    "carrot": (0.25, 0.75, DIAG),
    "fish": (0.15, 0.85, DIAG),
    "shovel": (0.15, 0.85, DIAG),
    "nodachi": (0.12, 0.88, DIAG),
}


def length(path, key):
    a = np.asarray(Image.open(path).convert("RGBA"))[:, :, 3] > 0
    h, w = a.shape
    ys, xs = np.nonzero(a)
    ox, oy, ang = TILTED.get(key, (0.12, 0.5, 0.0))
    # How far each pixel's far corner lies along the weapon, from where it's held.
    px = xs + 1 - ox * w
    py = ys + (0 if ang < 0 else 1) - oy * h
    along = px * math.cos(ang) + py * math.sin(ang)
    return round(float(along.max()), 1)


def main():
    art = Path(sys.argv[1])
    rows = [f"  {k}: {{ length: {length(art / f'{k}.png', k)} }}," for k in sys.argv[2:]]
    Path("src/sim/meleePoints.js").write_text(
        "// Generated by tools/melee_points.py from the melee weapon sprites: how far each one's tip\n"
        "// reaches from where it's held (px). Rerun the tool after changing melee art.\n"
        "export const MELEE_POINTS = {\n" + "\n".join(rows) + "\n};\n",
        encoding="utf-8",
    )
    print("\n".join(rows))


if __name__ == "__main__":
    main()
